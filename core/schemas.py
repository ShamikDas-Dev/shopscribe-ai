from __future__ import annotations

from pydantic import BaseModel, ConfigDict, Field, field_validator


class ProductFacts(BaseModel):
    """Verified product information supplied by the retailer."""

    model_config = ConfigDict(str_strip_whitespace=True, extra="forbid")

    product_name: str = Field(min_length=1, max_length=120)
    brand: str | None = Field(default=None, max_length=100)
    category: str = Field(default="General", min_length=1, max_length=80)
    verified_features: list[str] = Field(min_length=1, max_length=30)
    target_audience: str = Field(default="General shoppers", max_length=120)
    selling_price: float | None = Field(default=None, gt=0)
    mrp: float | None = Field(default=None, gt=0)

    @field_validator("verified_features")
    @classmethod
    def clean_features(cls, features: list[str]) -> list[str]:
        cleaned = [feature.strip() for feature in features if feature.strip()]
        if not cleaned:
            raise ValueError("Provide at least one verified product feature.")
        if any(len(feature) > 300 for feature in cleaned):
            raise ValueError("Each product fact must be 300 characters or fewer.")
        return cleaned


class ContentPack(BaseModel):
    """Structured content generated by the local model."""

    model_config = ConfigDict(extra="forbid")

    product_title: str = Field(min_length=1, max_length=100)
    product_description: str = Field(min_length=1, max_length=1200)
    instagram_caption: str = Field(min_length=1, max_length=1800)
    whatsapp_message: str = Field(min_length=1, max_length=1200)
    hashtags: list[str] = Field(default_factory=list, max_length=20)
    review_notes: list[str] = Field(default_factory=list, max_length=20)
